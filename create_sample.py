# سكريبت لإنشاء ملف Excel تجريبي للعملاء
# هنستخدمه عشان نتعلم القراءة من Excel

from openpyxl import Workbook

# 1. ننشئ Workbook جديد (ملف Excel فاضي)
wb = Workbook()

# 2. ناخد الشيت الأول ونسميه
ws = wb.active
ws.title = "العملاء"

# 3. نكتب صف العناوين (الـ Headers)
ws.append(["كود العميل", "اسم العميل", "رقم الجوال", "الموقع"])

# 4. نحضّر البيانات (5 عملاء تجريبيين)
customers = [
    ("C-1001", "فندق الزمزم", "0501234567", "العزيزية"),
    ("C-1002", "برج الفيصل", "0509876543", "العزيزية"),
    ("C-1003", "مستشفى النور", "0551122334", "الششة"),
    ("C-1004", "عمارة الأنصاري", "0556677889", "العوالي"),
    ("C-1005", "مجمع الصفوة", "0530001122", "الشرائع"),
]

# 5. نضيف كل عميل كصف في الإكسل
for customer in customers:
    ws.append(customer)

# 6. نحفظ الملف باسم customers.xlsx
wb.save("customers.xlsx")

print("✅ تم إنشاء ملف customers.xlsx بنجاح!")
print(f"📊 عدد العملاء: {len(customers)}")