for i, row in enumerate(INSTALL_PARTS):
    cat, desc, unit, rule, price = row
    desc = desc.replace('hilti', 'هilti').replace('هilti', 'هيلتي')
    desc = desc.replace('سkك', 'سكك').replace('ملm', 'ملم')
    INSTALL_PARTS[i] = (cat, desc, unit, rule, price)


def _safe_int(value, default=0, minimum=0):
    try:
        n = int(float(value or 0))
    except (TypeError, ValueError):
        n = default
    return max(n, minimum)


def _safe_float(value, default=0.0):
    try:
        return float(value or 0)
    except (TypeError, ValueError):
        return default


def build_qty_context(spec: dict[str, Any]) -> dict[str, float | int]:
    floors = _safe_int(spec.get('floors'), 2, minimum=2)
    stops = _safe_int(spec.get('stops'), floors, minimum=2)
    if stops > floors:
        stops = floors
    doors = _safe_int(spec.get('doors_count'), stops, minimum=1)
    travel_m = _safe_float(spec.get('travel_m'))
    if travel_m <= 0:
        travel_m = max(floors - 1, 1) * 3.2
    return {
        'floors': floors,
        'stops': stops,
        'doors': doors,
        'floors_minus_1': max(floors - 1, 1),
        'doors_right': max((doors + 1) // 2, 1),
        'doors_left': max(doors // 2, 1),
        'rope_segments': max(math.ceil(travel_m / 12), 1),
        'wire_runs': stops + 2,
        'stops_x2': stops * 2,
    }


def resolve_quantity(rule: str, ctx: dict[str, float | int]) -> float:
    if rule.startswith('fixed:'):
        return max(_safe_float(rule.split(':', 1)[1]), 0)
    if rule in ctx:
        return float(ctx[rule])
    return 1.0


def installation_material_lines(spec: dict[str, Any], line_fn) -> list[dict]:
    """يُرجع بنود مواد التركيب التفصيلية."""
    ctx = build_qty_context(spec)
    lines = []
    for category, description, unit, qty_rule, default_price in INSTALL_PARTS:
        qty = resolve_quantity(qty_rule, ctx)
        if qty <= 0:
            continue
        lines.append(line_fn(category, description, qty, unit, default_price))
    return lines
